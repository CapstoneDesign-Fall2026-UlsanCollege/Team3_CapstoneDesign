"""Browser role/MFA acceptance using a private, ephemeral test-only mail outbox."""
import json
from playwright.sync_api import expect


def run_security_scenarios(browser, page, context, check, output, password, origin, outbox):
    def latest(email, field="code"):
        matches = [(path.stat().st_mtime_ns, json.loads(path.read_text())) for path in outbox.glob("*.json")]
        return max((item for item in matches if item[1]["to"] == email and field in item[1]), key=lambda item: item[0])[1][field]

    def verify_email(target, email):
        expect(target.get_by_role("heading", name="Check your email.")).to_be_visible()
        target.get_by_label("Email code or one-use recovery code", exact=True).fill(latest(email))
        target.get_by_role("button", name="Verify & sign in", exact=True).click()
        expect(target.get_by_role("heading", name="Keep your recovery codes safe.")).to_be_visible()
        target.get_by_label("I have saved my recovery codes privately", exact=False).check()
        target.get_by_role("button", name="Enter my workspace", exact=False).click()

    def post(ctx, path, data=None):
        csrf = ctx.request.get(origin + "/auth/session").json().get("csrf_token", "")
        return ctx.request.post(origin + path, data=data, headers={"X-CSRF-Token": csrf})

    page.goto(origin)
    expect(page.get_by_role("heading", name="Your business. Your own POS.")).to_be_visible()
    page.get_by_role("button", name="Inventory", exact=True).click()
    expect(page.get_by_role("table", name="Inventory example")).to_be_visible()
    page.get_by_role("navigation", name="Site navigation").get_by_role("link", name="Register").click()
    expect(page).to_have_url(origin + "/register")
    expect(page.get_by_role("heading", name="Create your business")).to_be_visible()
    page.go_back()
    page.get_by_role("navigation", name="Site navigation").get_by_role("link", name="Sign in").click()
    expect(page).to_have_url(origin + "/login")
    expect(page.get_by_role("heading", name="Welcome back.")).to_be_visible()
    check("no public admin registration link", 0, page.get_by_role("link", name="Register", exact=False).count())
    page.screenshot(path=str(output / "security-01-sign-in.png"), full_page=True)
    page.get_by_label("Email address", exact=True).fill("browser-admin@example.test")
    page.get_by_label("Passphrase", exact=True).fill(password)
    page.get_by_role("button", name="Sign in", exact=True).click()
    expect(page.get_by_role("heading", name="Check your email.")).to_be_visible()
    check("admin password does not bypass email verification", 401, context.request.get(origin + "/platform/businesses").status)
    page.screenshot(path=str(output / "security-02-email-verification.png"), full_page=True)
    verify_email(page, "browser-admin@example.test")
    expect(page.get_by_role("heading", name="Your business platform")).to_be_visible()
    original_businesses = context.request.get(origin + "/platform/businesses").json()
    page.screenshot(path=str(output / "security-03-platform-console.png"), full_page=True)
    check("platform has no business creation button", 0, page.get_by_role("button", name="Add business").count())
    check("platform cannot create a workspace by API", 405, post(context, "/platform/businesses", {"name": "Blocked"}).status)
    alpha_context = browser.new_context(viewport={"width": 1440, "height": 1080})
    alpha_page = alpha_context.new_page()
    alpha_page.goto(origin + "/register")
    alpha_page.get_by_label("Business name").fill("Alpha Café")
    alpha_page.get_by_label("Email address").fill("creator-alpha@example.test")
    alpha_page.get_by_role("button", name="Email me a signup link").click()
    expect(alpha_page.get_by_role("heading", name="Check your inbox")).to_be_visible()
    expect(alpha_page.get_by_role("button", name="Resend in", exact=False)).to_be_disabled()
    expect(alpha_page.get_by_role("status")).to_contain_text("link to create your owner account")
    alpha_page.goto(latest("creator-alpha@example.test", "activation_url"))
    alpha_page.get_by_label("Your name").fill("Alpha founder")
    alpha_page.get_by_label("Passphrase").fill(password)
    alpha_page.get_by_role("button", name="Activate my account").click()
    verify_email(alpha_page, "creator-alpha@example.test")
    expect(alpha_page).to_have_url(origin + "/setup")
    expect(alpha_page.get_by_role("heading", name="What kind of business are you building?")).to_be_visible()
    check("setup has exactly three steps", 3, alpha_page.get_by_role("list", name="Setup steps").locator("li").count())
    alpha_page.locator(".business-choice").filter(has_text="Café").click()
    alpha_page.get_by_role("button", name="Continue", exact=False).click()
    alpha_page.get_by_role("button", name="Takeaway only", exact=False).click()
    alpha_page.screenshot(path=str(output / "new-business-02-workflow.png"), full_page=True)
    alpha_page.get_by_role("button", name="Continue", exact=False).click()
    alpha_page.get_by_label("Business name", exact=True).fill("")
    alpha_page.get_by_role("button", name="Create my workspace", exact=False).click()
    expect(alpha_page.get_by_role("alert")).to_have_text("Enter your business name.")
    check("incomplete setup creates no additional business", len(original_businesses) + 1, len(context.request.get(origin + "/platform/businesses").json()))
    alpha_page.get_by_label("Business name", exact=True).fill("Alpha Café")
    alpha_page.get_by_role("button", name="Start with editable sample items", exact=False).click()
    alpha_page.locator(".setup-footer").get_by_role("button", name="Back", exact=False).click()
    expect(alpha_page.get_by_role("button", name="Takeaway only", exact=False)).to_have_attribute("aria-pressed", "true")
    alpha_page.get_by_role("button", name="Continue", exact=False).click()
    expect(alpha_page.get_by_label("Business name", exact=True)).to_have_value("Alpha Café")
    expect(alpha_page.get_by_role("button", name="Start with editable sample items", exact=False)).to_have_attribute("aria-pressed", "true")
    alpha_page.screenshot(path=str(output / "new-business-03-details-review.png"), full_page=True)
    alpha_page.set_viewport_size({"width": 390, "height": 844})
    check("mobile details and review fit the screen", True, alpha_page.evaluate("document.documentElement.scrollWidth <= window.innerWidth"))
    alpha_page.screenshot(path=str(output / "new-business-04-mobile-review.png"), full_page=True)
    alpha_page.set_viewport_size({"width": 1440, "height": 1080})
    alpha_page.route("**/owner/business/setup", lambda route: route.fulfill(status=503, json={"detail": "Temporary setup interruption. Please retry."}))
    alpha_page.get_by_role("button", name="Create my workspace", exact=False).click()
    expect(alpha_page.get_by_role("alert")).to_have_text("Temporary setup interruption. Please retry.")
    check("interrupted setup preserves one resumable business", len(original_businesses) + 1, len(context.request.get(origin + "/platform/businesses").json()))
    alpha_page.unroute("**/owner/business/setup")
    alpha_page.get_by_role("button", name="Create my workspace", exact=False).click()
    expect(alpha_page.get_by_role("link", name="Open my POS", exact=False)).to_be_visible()
    businesses = context.request.get(origin + "/platform/businesses").json()
    check("completed setup provisions exactly one business", len(original_businesses) + 1, len(businesses))
    store = next(item for item in businesses if item["name"] == "Alpha Café")
    alpha_page.get_by_role("link", name="Open my POS", exact=False).click()
    expect(alpha_page.get_by_role("heading", name="Alpha Café", exact=True, level=1)).to_be_visible()
    alpha_context.close()
    check("admin can select an existing business", 200, post(context, "/auth/switch-business", {"store_id": store["id"]}).status)
    page.goto(origin + "/platform")
    page.get_by_label("Business", exact=True).select_option(store["id"])
    page.get_by_label("Owner name", exact=True).fill("Alex Owner")
    page.get_by_label("Owner email", exact=True).fill("owner-alpha@example.test")
    page.get_by_role("button", name="Email owner invitation").click()
    expect(page.get_by_role("status")).to_contain_text("email")
    owner_url = latest("owner-alpha@example.test", "activation_url")
    owner_context = browser.new_context(viewport={"width": 1440, "height": 1080})
    owner_page = owner_context.new_page()
    owner_page.route("**/docs.google.com/**", lambda route: route.abort())
    owner_page.goto(owner_url)
    owner_page.get_by_label("Your name", exact=True).fill("Alex Owner")
    owner_page.get_by_label("Passphrase", exact=True).fill(password)
    owner_page.get_by_role("button", name="Activate my account").click()
    verify_email(owner_page, "owner-alpha@example.test")
    expect(owner_page.get_by_role("heading", name="Owner sales dashboard")).to_be_visible()
    check("owner has no platform link", 0, owner_page.get_by_role("link", name="Platform admin", exact=True).count())
    check("owner can edit business setup", 1, owner_page.get_by_role("button", name="Edit business profile", exact=True).count())
    owner_page.screenshot(path=str(output / "security-04-owner-dashboard.png"), full_page=True)
    owner_page.get_by_label("Staff name", exact=True).fill("Riley Cashier")
    owner_page.get_by_label("Staff email", exact=True).fill("cashier-alpha@example.test")
    owner_page.get_by_role("button", name="Create private staff invitation", exact=True).click()
    cashier_link = owner_page.get_by_label("Private staff activation link", exact=True)
    expect(cashier_link).to_be_visible()
    cashier_context = browser.new_context(viewport={"width": 1440, "height": 1080})
    cashier_page = cashier_context.new_page()
    cashier_page.goto(cashier_link.input_value())
    cashier_page.get_by_label("Your name", exact=True).fill("Riley Cashier")
    cashier_page.get_by_label("Passphrase", exact=True).fill(password)
    cashier_page.get_by_role("button", name="Activate my account").click()
    verify_email(cashier_page, "cashier-alpha@example.test")
    expect(cashier_page.locator(".menu-card")).to_have_count(3)
    check("cashier has no owner dashboard nav", 0, cashier_page.get_by_role("button", name="Owner dashboard", exact=True).count())
    check("cashier sales API denied", 403, cashier_context.request.get(origin + "/dashboard/sales").status)
    check("cashier staff API denied", 403, cashier_context.request.get(origin + "/owner/staff").status)
    cashier_page.locator(".menu-card").filter(has_text="Espresso").click()
    cashier_page.get_by_role("button", name="Pay cash", exact=True).click()
    expect(cashier_page.locator(".receipt")).to_contain_text("3,000")
    cashier_page.screenshot(path=str(output / "security-05-cashier-checkout.png"), full_page=True)
    owner_page.goto(origin + "/setup")
    expect(owner_page.get_by_role("heading", name="What kind of business are you building?")).to_be_visible()
    check("cashier setup API denied", 403, post(cashier_context, "/owner/business/setup", {"name": "No", "business_type": "cafe", "operation_mode": "takeaway"}).status)
    cashier_page.goto(origin + "/platform")
    expect(cashier_page.get_by_role("heading", name="Platform administrator access required.")).to_be_visible()
    check("cross-business selection denied for owner", 403, post(owner_context, "/auth/switch-business", {"store_id": "legacy"}).status)
    signup_context = browser.new_context()
    signup_page = signup_context.new_page()
    signup_page.goto(origin + "/login")
    signup_page.get_by_role("link", name="Create your own business").click()
    expect(signup_page).to_have_url(origin + "/register")
    signup_page.get_by_label("Business name").fill("Independent Cafe")
    signup_page.get_by_label("Email address").fill("independent@example.test")
    signup_page.get_by_role("button", name="Email me a signup link").click()
    expect(signup_page.get_by_role("status")).to_contain_text("link to create your owner account")
    check("signup request does not provision a workspace", len(businesses), len(context.request.get(origin + "/platform/businesses").json()))
    signup_page.goto(latest("independent@example.test", "activation_url"))
    signup_page.get_by_label("Your name").fill("Independent Owner")
    signup_page.get_by_label("Passphrase").fill(password)
    signup_page.get_by_role("button", name="Activate my account").click()
    verify_email(signup_page, "independent@example.test")
    expect(signup_page).to_have_url(origin + "/setup")
    signup_page.get_by_role("button", name="Café", exact=False).click()
    signup_page.get_by_role("button", name="Continue", exact=False).click()
    expect(signup_page).to_have_url(origin + "/setup?step=2")
    signup_page.go_back()
    expect(signup_page).to_have_url(origin + "/setup")
    expect(signup_page.get_by_role("button", name="Café", exact=False)).to_have_attribute("aria-pressed", "true")
    signup_page.go_forward()
    expect(signup_page).to_have_url(origin + "/setup?step=2")
    signup_page.get_by_role("button", name="Continue", exact=False).click()
    expect(signup_page.get_by_label("Business name")).to_have_value("Independent Cafe")
    signup_page.get_by_label("Business name").fill("Independent Coffee")
    signup_page.get_by_label("Business address").fill("24 Market Street")
    signup_page.goto(origin + "/login")
    expect(signup_page).to_have_url(origin + "/setup?step=3")
    expect(signup_page.get_by_label("Business name")).to_have_value("Independent Coffee")
    expect(signup_page.get_by_label("Business address")).to_have_value("24 Market Street")
    signup_page.get_by_role("button", name="Back", exact=False).click()
    expect(signup_page).to_have_url(origin + "/setup?step=2")
    signup_page.get_by_role("button", name="Continue", exact=False).click()
    signup_page.get_by_label("Phone country").select_option("KR")
    signup_page.get_by_label("Phone (optional)").fill("+1 202-555-0123")
    signup_page.get_by_role("button", name="Create my workspace", exact=False).click()
    expect(signup_page.get_by_role("alert")).to_contain_text("valid phone number for the selected country")
    signup_page.get_by_label("Phone (optional)").fill("010-1234-5678")
    signup_page.get_by_role("button", name="Create my workspace", exact=False).click()
    signup_page.get_by_role("link", name="Open my POS", exact=False).click()
    expect(signup_page).to_have_url(origin + "/pos/dashboard")
    signup_page.get_by_role("button", name="Orders", exact=True).click()
    signup_page.get_by_role("button", name="Trash", exact=True).click()
    expect(signup_page).to_have_url(origin + "/pos/orders/trash")
    signup_page.go_back()
    expect(signup_page.get_by_role("heading", name="Orders", exact=True)).to_be_visible()
    signup_page.go_forward()
    signup_page.reload()
    expect(signup_page.get_by_role("heading", name="Order Trash", exact=True)).to_be_visible()
    check("self-service signup has only its own owner membership", ["owner"],
          [item["role"] for item in signup_context.request.get(origin + "/auth/session").json()["businesses"]])
    check("self-service signup cannot access platform", 403, signup_context.request.get(origin + "/platform/businesses").status)
    signup_context.close()
    owner_context.close()
    cashier_context.close()
    page.goto(origin + "/login")
    expect(page.get_by_role("heading", name="Alpha Café", exact=True)).to_be_visible()
