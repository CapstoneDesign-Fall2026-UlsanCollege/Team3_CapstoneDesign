"""Browser role/MFA acceptance using a private, ephemeral test-only mail outbox."""
import json
from playwright.sync_api import expect


def run_security_scenarios(browser, page, context, check, output, password, origin, outbox):
    def latest(email):
        matches = [(path.stat().st_mtime_ns, json.loads(path.read_text())) for path in outbox.glob("*.json")]
        return max((item for item in matches if item[1]["to"] == email), key=lambda item: item[0])[1]["code"]

    def verify_email(target, email):
        expect(target.get_by_role("heading", name="Check your email.")).to_be_visible()
        target.get_by_label("Email code or one-use recovery code", exact=True).fill(latest(email))
        target.get_by_role("button", name="Verify & sign in", exact=True).click()
        expect(target.get_by_role("heading", name="Keep your recovery codes safe.")).to_be_visible()
        target.get_by_label("I have saved my recovery codes privately", exact=False).check()
        target.get_by_role("button", name="Enter my workspace", exact=False).click()

    def post(ctx, path, data=None):
        csrf = ctx.request.get(origin + "/auth/session").json().get("csrf_token", "")
        return ctx.request.post(origin + path, data=data, headers={"X-CSRF-Token": csrf})

    page.goto(origin)
    expect(page.get_by_role("heading", name="Sign in to SmartServe")).to_be_visible()
    check("no public admin registration link", 0, page.get_by_role("link", name="Register", exact=False).count())
    page.screenshot(path=str(output / "security-01-sign-in.png"), full_page=True)
    page.get_by_label("Email address", exact=True).fill("browser-admin@example.test")
    page.get_by_label("Passphrase", exact=True).fill(password)
    page.get_by_role("button", name="Sign in", exact=True).click()
    expect(page.get_by_role("heading", name="Check your email.")).to_be_visible()
    check("admin password does not bypass email verification", 401, context.request.get(origin + "/platform/businesses").status)
    page.screenshot(path=str(output / "security-02-email-verification.png"), full_page=True)
    verify_email(page, "browser-admin@example.test")
    expect(page.get_by_role("heading", name="Your business platform")).to_be_visible()
    page.get_by_label("Business account name", exact=True).fill("Workspace Alpha")
    page.get_by_role("button", name="Create business", exact=True).click()
    expect(page.locator(".business-account").filter(has_text="Workspace Alpha")).to_be_visible()
    businesses = context.request.get(origin + "/platform/businesses").json()
    store = next(item for item in businesses if item["name"] == "Workspace Alpha")
    page.screenshot(path=str(output / "security-03-platform-console.png"), full_page=True)
    page.locator(".business-account").filter(has_text="Workspace Alpha").get_by_role("button", name="Configure setup").click()
    page.locator(".business-choice").filter(has_text="Café").click()
    page.get_by_role("button", name="Continue", exact=False).click()
    page.get_by_role("button", name="Takeaway only", exact=False).click()
    page.get_by_role("button", name="Continue", exact=False).click()
    page.get_by_label("Business name", exact=True).fill("Alpha Café")
    page.get_by_role("button", name="Continue", exact=False).click()
    page.get_by_role("button", name="Start with editable sample items", exact=False).click()
    page.get_by_role("button", name="Continue", exact=False).click()
    page.get_by_role("button", name="Create my workspace", exact=False).click()
    page.get_by_role("link", name="Open my POS", exact=False).click()
    expect(page.get_by_role("heading", name="Alpha Café", exact=True)).to_be_visible()
    page.goto(origin + "/platform")
    page.get_by_label("Business", exact=True).select_option(store["id"])
    page.get_by_label("Owner name", exact=True).fill("Alex Owner")
    page.get_by_label("Owner email", exact=True).fill("owner-alpha@example.test")
    page.get_by_role("button", name="Email owner invitation", exact=True).click()
    expect(page.get_by_text("Owner activation email sent.", exact=True)).to_be_visible()
    messages = [json.loads(path.read_text()) for path in outbox.glob("*.json")]
    owner_url = next(item["activation_url"] for item in messages if item["to"] == "owner-alpha@example.test")
    owner_context = browser.new_context(viewport={"width": 1440, "height": 1080})
    owner_page = owner_context.new_page()
    owner_page.route("**/docs.google.com/**", lambda route: route.abort())
    owner_page.goto(owner_url)
    owner_page.get_by_label("Your name", exact=True).fill("Alex Owner")
    owner_page.get_by_label("Passphrase", exact=True).fill(password)
    owner_page.get_by_role("button", name="Activate my account").click()
    verify_email(owner_page, "owner-alpha@example.test")
    expect(owner_page.get_by_role("heading", name="Owner sales dashboard")).to_be_visible()
    check("owner has no platform link", 0, owner_page.get_by_role("link", name="Platform admin", exact=True).count())
    check("owner has no setup button", 0, owner_page.get_by_role("button", name="Edit business profile", exact=True).count())
    check("owner cannot call setup API", 403, post(owner_context, "/owner/business/setup", {"name": "No", "business_type": "cafe", "operation_mode": "takeaway"}).status)
    owner_page.screenshot(path=str(output / "security-04-owner-dashboard.png"), full_page=True)
    owner_page.get_by_label("Staff name", exact=True).fill("Riley Cashier")
    owner_page.get_by_label("Staff email", exact=True).fill("cashier-alpha@example.test")
    owner_page.get_by_role("button", name="Create private staff invitation", exact=True).click()
    cashier_link = owner_page.get_by_label("Private staff activation link", exact=True)
    expect(cashier_link).to_be_visible()
    cashier_context = browser.new_context(viewport={"width": 1440, "height": 1080})
    cashier_page = cashier_context.new_page()
    cashier_page.goto(cashier_link.input_value())
    cashier_page.get_by_label("Your name", exact=True).fill("Riley Cashier")
    cashier_page.get_by_label("Passphrase", exact=True).fill(password)
    cashier_page.get_by_role("button", name="Activate my account").click()
    verify_email(cashier_page, "cashier-alpha@example.test")
    expect(cashier_page.locator(".menu-card")).to_have_count(3)
    check("cashier has no owner dashboard nav", 0, cashier_page.get_by_role("button", name="Owner dashboard", exact=True).count())
    check("cashier sales API denied", 403, cashier_context.request.get(origin + "/dashboard/sales").status)
    check("cashier staff API denied", 403, cashier_context.request.get(origin + "/owner/staff").status)
    cashier_page.locator(".menu-card").filter(has_text="Espresso").click()
    cashier_page.get_by_role("button", name="Pay cash", exact=True).click()
    expect(cashier_page.locator(".receipt")).to_contain_text("3,000")
    cashier_page.screenshot(path=str(output / "security-05-cashier-checkout.png"), full_page=True)
    owner_page.goto(origin + "/setup")
    expect(owner_page.get_by_role("heading", name="Setup is managed by your platform administrator.")).to_be_visible()
    cashier_page.goto(origin + "/platform")
    expect(cashier_page.get_by_role("heading", name="Platform administrator access required.")).to_be_visible()
    check("cross-business selection denied for owner", 403, post(owner_context, "/auth/switch-business", {"store_id": "legacy"}).status)
    owner_context.close()
    cashier_context.close()
    page.goto(origin + "/")
    expect(page.get_by_role("heading", name="Alpha Café", exact=True)).to_be_visible()
