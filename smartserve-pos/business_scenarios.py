"""User-facing onboarding and workflow acceptance scenarios."""
from datetime import datetime, timedelta
from playwright.sync_api import expect


def run_scenarios(page, context, check, output, password, origin):
    def shot(name):
        page.screenshot(path=str(output / name), full_page=True)

    def continue_setup():
        page.get_by_role("button", name="Continue", exact=False).click()

    def setup(kind, mode, name, catalog="samples", screenshots=False):
        page.goto(origin + "/setup")
        expect(page.get_by_role("heading", name="What kind of business are you building?")).to_be_visible()
        if screenshots:
            check("ten business choices including custom", 10, page.locator(".business-choice").count())
            shot("01-choose-business.png")
        page.locator(".business-choice").filter(has_text=kind).click()
        continue_setup()
        page.get_by_role("button", name=mode, exact=False).click()
        if screenshots:
            shot("02-choose-workflow.png")
        continue_setup()
        page.get_by_label("Business name", exact=True).fill(name)
        page.get_by_label("Business address", exact=True).fill("24 Market Street, Ulsan")
        if screenshots:
            shot("03-business-profile.png")
        continue_setup()
        page.get_by_role("button", name="Start with editable sample items" if catalog == "samples" else "Start with an empty catalog" if catalog == "empty" else "Keep my current catalog", exact=False).click()
        continue_setup()
        if screenshots:
            shot("04-review-profile.png")
        page.get_by_role("button", name="Create my workspace", exact=False).click()
        expect(page.get_by_role("link", name="Open my POS", exact=False)).to_be_visible()
        page.get_by_role("link", name="Open my POS", exact=False).click()
        expect(page.get_by_role("heading", name=name, exact=True)).to_be_visible()

    def sell(item):
        page.locator(".menu-card").filter(has_text=item).click()
        page.get_by_role("button", name="Pay cash", exact=True).click()
        expect(page.locator(".receipt")).to_be_visible()

    baseline_paid = len([order for order in context.request.get(origin + "/orders").json() if order["status"] == "paid"])
    setup("Café", "Takeaway + tables", "Sunday Coffee", screenshots=True)
    check("profile completed", True, context.request.get(origin + "/business").json()["onboarding_complete"])
    check("only cafe starter catalog visible", 3, page.locator(".menu-card").count())
    page.get_by_role("button", name="Tables", exact=True).click()
    page.locator(".floor-table").filter(has_text="Table 1").click()
    page.locator(".menu-card").filter(has_text="Espresso").click()
    page.get_by_role("button", name="Create order", exact=True).click()
    expect(page.get_by_role("status")).to_contain_text("created")
    page.reload()
    expect(page.locator(".total")).to_contain_text("3,000")
    page.locator(".menu-card").filter(has_text="Espresso").click()
    page.get_by_role("button", name="Add items to bill", exact=True).click()
    expect(page.locator(".total")).to_contain_text("6,000")
    page.get_by_role("button", name="Tables", exact=True).click()
    shot("05-table-bills.png")
    page.locator(".floor-table").filter(has_text="Table 1").click()
    page.get_by_role("button", name="Pay cash", exact=True).click()
    expect(page.locator(".receipt")).to_contain_text("6,000")
    check("table freed after payment", None, context.request.get(origin + "/tables").json()[0]["order_id"])
    setup("Café", "Takeaway only", "Sunday To Go", catalog="keep")
    check("takeaway-only order type", ["takeaway"], page.locator("aside.panel select").first.locator("option").evaluate_all("els => els.map(el => el.value)"))
    check("no tables nav for takeaway-only", 0, page.get_by_role("button", name="Tables", exact=True).count())
    setup("Retail shop", "In store + pickup", "Everyday Store")
    page.get_by_label("Search items", exact=True).fill("RETAIL-001")
    expect(page.locator(".menu-card")).to_have_count(1)
    sell("Cotton T-shirt")
    stock = context.request.get(origin + "/inventory").json()
    check("retail deducts one piece", 39, next(item["stock_quantity"] for item in stock if item["name"] == "T-shirt stock"))
    shot("06-retail-checkout.png")
    setup("Barbershop", "Walk-ins + appointments", "The Local Barber")
    page.get_by_role("button", name="Appointments & jobs", exact=True).click()
    page.get_by_label("Service", exact=True).fill("Classic haircut")
    page.get_by_label("Customer name", exact=True).fill("Alex Demo")
    page.get_by_label("Staff / resource", exact=True).fill("Sam")
    time = (datetime.now() + timedelta(days=1)).replace(hour=10, minute=0, second=0, microsecond=0).strftime("%Y-%m-%dT%H:%M")
    page.get_by_label("Appointment time (your local time)", exact=True).fill(time)
    page.get_by_role("button", name="Book appointment", exact=True).click()
    expect(page.get_by_role("status")).to_contain_text("Appointment booked")
    shot("07-appointments.png")
    appointment = context.request.get(origin + "/owner/work").json()[0]
    clash = context.request.post(origin + "/owner/work", data={"kind": "appointment", "title": "Another cut", "customer": "Other customer", "resource": "sam", "starts_at": appointment["starts_at"], "duration_minutes": 30}, headers={"X-CSRF-Token": context.request.get(origin + "/auth/session").json()["csrf_token"]})
    check("overlapping staff booking rejected", 409, clash.status)
    page.locator(".work-card").get_by_role("button", name="Checkout", exact=True).click()
    sell("Classic haircut")
    check("appointment completed after payment", "completed", context.request.get(origin + "/owner/work").json()[0]["status"])
    page.get_by_role("button", name="Appointments & jobs", exact=True).click()
    page.get_by_role("button", name="Walk-ins", exact=True).click()
    page.get_by_label("Service", exact=True).fill("Beard trim")
    page.get_by_label("Customer name", exact=True).fill("Robin Demo")
    page.get_by_role("button", name="Add to queue", exact=True).click()
    expect(page.get_by_role("status")).to_contain_text("added to the queue")
    page.get_by_role("button", name="Start work", exact=True).click()
    page.get_by_role("button", name="Mark ready", exact=True).click()
    page.get_by_role("button", name="Checkout", exact=True).click()
    sell("Beard trim")
    setup("Repair & workshop", "Immediate service + jobs", "Fix & Go")
    page.get_by_role("button", name="Appointments & jobs", exact=True).click()
    page.get_by_label("Repair / device", exact=True).fill("Phone screen repair")
    page.get_by_label("Customer name", exact=True).fill("Morgan Demo")
    page.get_by_label("Fault, device details & customer instructions", exact=True).fill("Cracked screen. Please call before replacing parts.")
    page.get_by_role("button", name="Create repair job", exact=True).click()
    expect(page.get_by_role("status")).to_contain_text("Repair job created")
    page.get_by_role("button", name="Start work", exact=True).click()
    page.get_by_role("button", name="Mark ready", exact=True).click()
    shot("08-repair-jobs.png")
    page.get_by_role("button", name="Checkout", exact=True).click()
    sell("Repair diagnosis")
    check("repair job completed after payment", "completed", context.request.get(origin + "/owner/work").json()[0]["status"])
    setup("Custom setup", "Build my own workflow", "My Own Business", catalog="empty")
    check("custom empty catalog", 0, page.locator(".menu-card").count())
    check("previous sales retained", baseline_paid + 5, len([order for order in context.request.get(origin + "/orders").json() if order["status"] == "paid"]))
    page.goto(origin + "/etalogin")
    page.locator("summary").filter(has_text="Add item").click()
    page.get_by_label("Item name", exact=True).fill("My custom service")
    page.get_by_label("Price (KRW)", exact=True).fill("22000")
    page.get_by_label("Item type", exact=True).select_option("service")
    page.get_by_label("Category", exact=True).fill("My services")
    page.get_by_role("button", name="Add item", exact=True).click()
    expect(page.get_by_role("status")).to_contain_text("My custom service")
    page.goto(origin)
    sell("My custom service")
    check("custom catalog checkout", 22000, context.request.get(origin + "/orders").json()[0]["total"])
    page.set_viewport_size({"width": 390, "height": 844})
    page.goto(origin + "/setup")
    expect(page.get_by_role("heading", name="What kind of business are you building?")).to_be_visible()
    shot("09-mobile-onboarding.png")
    check("mobile setup fits screen", True, page.locator(".setup-shell").evaluate("el => el.scrollWidth <= window.innerWidth"))
